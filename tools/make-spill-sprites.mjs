mkdirSync(dir, { recursive: true });
for (const [name, [palette, rows]] of Object.entries(sprites)) {
  const colours = palettes[palette], width = Math.max(...rows.map(row => row.length));
  const rects = rows.flatMap((row, y) => [...row].map((ch, x) => colours[ch] ? `<rect x="${x}" y="${y}" width="1" height="1" fill="${colours[ch]}"/>` : '')).join('');
  writeFileSync(`${dir}/${name}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${rows.length}" viewBox="0 0 ${width} ${rows.length}" shape-rendering="crispEdges"><!-- Generated by tools/make-spill-sprites.mjs. -->${rects}</svg>\n`);
}
