// Small pixel decals that one tile scatters across its edge onto an unlike
// neighbour (tileSpill.ts): den pebbles, berry sprigs and dirt clods. Palettes
// come from the den, berry patch and dirt ground art. Each character is one
// pixel; '.' is transparent. Run: node tools/make-spill-sprites.mjs
